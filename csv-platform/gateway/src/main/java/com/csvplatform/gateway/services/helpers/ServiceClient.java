package com.csvplatform.gateway.services.helpers;

import java.io.IOException;
import java.io.InterruptedIOException;
import java.net.URI;
import java.net.http.HttpClient;
import java.net.http.HttpRequest;
import java.net.http.HttpResponse;
import java.time.Duration;

/**
 * Calls the Analysis (Jetty) and Cleaning (WildFly) services over HTTP.
 */
public class ServiceClient {

    private static final Duration CONNECT_TIMEOUT = Duration.ofSeconds(2);
    private static final Duration HEALTH_TIMEOUT = Duration.ofSeconds(2);
    private static final Duration CALL_TIMEOUT = Duration.ofSeconds(60);

    private final HttpClient http = HttpClient.newBuilder().connectTimeout(CONNECT_TIMEOUT).build();
    private final String analysisUrl;
    private final String cleaningUrl;

    public ServiceClient(String analysisUrl, String cleaningUrl) {
        this.analysisUrl = stripTrailingSlash(analysisUrl);
        this.cleaningUrl = stripTrailingSlash(cleaningUrl);
    }

    /**
     * Asks Analysis to analyze the job's original.csv and write report.json.
     * @throws IOException if Analysis is unreachable or times out
     * @throws IllegalStateException if Analysis answers with a non-2xx status
     */
    public void analyze(String jobId) throws IOException {
        post("ANALYSIS", analysisUrl + "/analyze", jobId);
    }

    /**
     * Asks Cleaning to produce cleaned.csv from original.csv and report.json.
     * @throws IOException if Cleaning is unreachable or times out
     * @throws IllegalStateException if Cleaning answers with a non-2xx status
     */
    public void clean(String jobId) throws IOException {
        post("CLEANING", cleaningUrl + "/clean", jobId);
    }

    public boolean isAnalysisUp() {
        return isUp(analysisUrl);
    }

    public boolean isCleaningUp() {
        return isUp(cleaningUrl);
    }

    private void post(String service, String url, String jobId) throws IOException {
        // jobId is a UUID generated by the Gateway, so it needs no JSON escaping
        HttpRequest request = HttpRequest.newBuilder(URI.create(url))
                .timeout(CALL_TIMEOUT)
                .header("Content-Type", "application/json")
                .POST(HttpRequest.BodyPublishers.ofString("{\"jobId\":\"" + jobId + "\"}"))
                .build();

        HttpResponse<String> response = send(request);
        int status = response.statusCode();
        if (status < 200 || status >= 300) {
            throw new IllegalStateException(service + " returned HTTP " + status + ": " + response.body());
        }
    }

    private boolean isUp(String baseUrl) {
        HttpRequest request = HttpRequest.newBuilder(URI.create(baseUrl + "/health"))
                .timeout(HEALTH_TIMEOUT).GET().build();
        try {
            return send(request).statusCode() == 200;
        } catch (IOException e) {
            return false;
        }
    }

    private HttpResponse<String> send(HttpRequest request) throws IOException {
        try {
            return http.send(request, HttpResponse.BodyHandlers.ofString());
        } catch (InterruptedException e) {
            Thread.currentThread().interrupt();
            throw new InterruptedIOException("Interrupted while calling " + request.uri());
        }
    }

    private static String stripTrailingSlash(String url) {
        return url.endsWith("/") ? url.substring(0, url.length() - 1) : url;
    }
}